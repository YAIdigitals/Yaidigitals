-- Function to auto-increment view/download counts
CREATE OR REPLACE FUNCTION public.increment_resource_counter()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF NEW.event_type = 'view' THEN
    UPDATE public.resources SET view_count = view_count + 1 WHERE id = NEW.resource_id;
  ELSIF NEW.event_type = 'download_click' THEN
    UPDATE public.resources SET download_count = download_count + 1 WHERE id = NEW.resource_id;
  END IF;
  RETURN NEW;
END;
$$;

CREATE TRIGGER trg_increment_resource_counter
  AFTER INSERT ON public.resource_events
  FOR EACH ROW EXECUTE FUNCTION public.increment_resource_counter();
